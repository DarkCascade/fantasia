'use strict';

const fs = require('fs');
const path = require('path');

let _index = null;
function loadIndex() {
  if (!_index) {
    _index = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'index', 'passives.json'), 'utf8'));
  }
  return _index;
}

// Every node in the raw export carries the numeric tree-position id its
// in/out adjacency is expressed in. Build both directions of lookup once.
function buildLookups(index) {
  const byNumericId = {};
  for (const [stringId, n] of Object.entries(index.nodes)) {
    byNumericId[n.numericId] = stringId;
  }
  return byNumericId;
}

let _byNumericId = null;
function numericIdToStringId() {
  if (!_byNumericId) _byNumericId = buildLookups(loadIndex());
  return _byNumericId;
}

// Neighbours a route may step onto. Mastery nodes ("Spear Mastery", ...)
// are decorative hubs PoE2 kept from PoE1's tree art: they have edges in the
// export but no stats and can't be allocated (no real .build file allocates
// one), so a path through one is a path the player can't actually take.
function traversableNeighbours(node) {
  const index = loadIndex();
  const numToStr = numericIdToStringId();
  return [...node.in, ...node.out].filter((nid) => {
    const sid = numToStr[nid];
    return !(sid && index.nodes[sid].isMastery);
  });
}

// Finds every passive node whose display name matches (case-insensitive).
// Generic filler nodes ("Attribute", "Movement Speed", ...) are shared by
// dozens of nodes with no other distinguishing text — expect many matches
// for those and few (often exactly one) for notables/keystones/ascendancy
// nodes, which have distinctive names. Use `ascendancyId` to scope the
// search to one ascendancy's nodes when a name collides across classes.
function findPassivesByName(name, { ascendancyId } = {}) {
  const index = loadIndex();
  const needle = name.trim().toLowerCase();
  const matches = [];
  for (const [id, n] of Object.entries(index.nodes)) {
    if (n.name && n.name.toLowerCase() === needle) {
      if (ascendancyId && n.ascendancyId !== ascendancyId) continue;
      matches.push({ id, ...n });
    }
  }
  return matches;
}

// Convenience over findPassivesByName for the common case: exactly one
// match expected (a notable, keystone, or ascendancy node — anything with
// a distinctive enough name to be looked up this way at all). Throws with
// the full candidate list if that's not what happened, rather than
// silently picking one — a wrong passive silently swapped in is worse than
// a loud failure demanding disambiguation.
function resolvePassiveId(name, opts = {}) {
  const matches = findPassivesByName(name, opts);
  if (matches.length === 1) return matches[0].id;
  if (matches.length === 0) {
    throw new Error(`No passive node named "${name}" found${opts.ascendancyId ? ` in ascendancy ${opts.ascendancyId}` : ''}.`);
  }
  throw new Error(
    `"${name}" matches ${matches.length} passive nodes — ambiguous. ` +
      `Pass { ascendancyId } to narrow it, or use findPassivesByName() and pick by id: ` +
      matches.map((m) => m.id).join(', ')
  );
}

// The tree's 6 engine-level "class start" nodes are still internally
// labelled with PoE1's legacy class names (marauder594, witch595,
// ranger596, duelist597, templar598, six704) rather than PoE2's actual
// classes — some PoE2 classes share a starting corner (Witch shares
// witch595 with Sorceress; Ranger shares ranger596 with Huntress). This is
// resolved by BFS graph-distance from each start node to a representative
// node of each class's ascendancies: every class's ascendancy nodes
// cluster overwhelmingly closer to exactly one start node than the other
// five (distances of 1-5 vs. 15+), computed once and cached rather than
// hardcoded so it self-corrects if the tree's node ids are ever
// regenerated by a future `npm run refresh-data`.
let _classStartCache = null;
function computeClassStartMap() {
  if (_classStartCache) return _classStartCache;
  const index = loadIndex();
  const numToStr = numericIdToStringId();
  const starts = Object.entries(index.nodes).filter(([, n]) => n.classStartIndex);

  function bfsDistances(startNumericId) {
    const dist = new Map([[startNumericId, 0]]);
    let frontier = [startNumericId];
    let d = 0;
    while (frontier.length && d < 60) {
      const next = [];
      for (const nid of frontier) {
        const sid = numToStr[nid];
        const n = sid ? index.nodes[sid] : null;
        if (!n) continue;
        for (const nb of traversableNeighbours(n)) {
          if (!dist.has(nb)) {
            dist.set(nb, d + 1);
            next.push(nb);
          }
        }
      }
      frontier = next;
      d++;
    }
    return dist;
  }

  const startDistances = starts.map(([id, n]) => ({ id, dist: bfsDistances(n.numericId) }));
  const ascReps = {};
  for (const [id, n] of Object.entries(index.nodes)) {
    if (n.ascendancyId && !ascReps[n.ascendancyId]) ascReps[n.ascendancyId] = id;
  }

  const map = {}; // className -> start node string id
  for (const c of index.classes) {
    let best = null;
    let bestDist = Infinity;
    for (const a of c.ascendancies) {
      const repId = ascReps[a.id];
      if (!repId) continue;
      const repNumeric = index.nodes[repId].numericId;
      for (const sd of startDistances) {
        const d = sd.dist.get(repNumeric);
        if (d !== undefined && d < bestDist) {
          bestDist = d;
          best = sd.id;
        }
      }
    }
    if (best) map[c.name] = best;
  }
  _classStartCache = map;
  return map;
}

// Accepts either an ascendancy id ("Mercenary3") or its display name
// ("Gemling Legionnaire") and returns { id, name, className }. Needed so a
// build spec can name an ascendancy by whichever's more natural and still
// let the assembler find the right class-start node automatically.
function resolveAscendancyId(nameOrId) {
  const index = loadIndex();
  for (const c of index.classes) {
    for (const a of c.ascendancies) {
      if (a.id === nameOrId || (a.name && a.name.toLowerCase() === nameOrId.trim().toLowerCase())) {
        return { id: a.id, name: a.name, className: c.name };
      }
    }
  }
  throw new Error(`No ascendancy matches "${nameOrId}".`);
}

function getClassStartNodeId(className) {
  const map = computeClassStartMap();
  const id = map[className];
  if (!id) {
    throw new Error(
      `No start node found for class "${className}" (no ascendancy of that class has a placed node in this tree export yet). Known classes: ${Object.keys(map).join(', ')}`
    );
  }
  return id;
}

// Shortest path between two passive nodes (inclusive of both endpoints),
// by node count — the tree's edges are unweighted so BFS is exact, not a
// heuristic. Returns null if unreachable (shouldn't happen within one
// connected tree, but graph data from an upstream export earns the check).
function shortestPath(fromId, toId) {
  const index = loadIndex();
  const numToStr = numericIdToStringId();
  const fromNode = index.nodes[fromId];
  const toNode = index.nodes[toId];
  if (!fromNode) throw new Error(`Unknown passive id "${fromId}"`);
  if (!toNode) throw new Error(`Unknown passive id "${toId}"`);
  if (fromId === toId) return [fromId];

  const prev = new Map([[fromNode.numericId, null]]);
  let frontier = [fromNode.numericId];
  while (frontier.length) {
    const next = [];
    for (const nid of frontier) {
      const sid = numToStr[nid];
      const n = sid ? index.nodes[sid] : null;
      if (!n) continue;
      for (const nb of traversableNeighbours(n)) {
        if (!prev.has(nb)) {
          prev.set(nb, nid);
          if (nb === toNode.numericId) {
            const path = [nb];
            let cur = nid;
            while (cur !== null) {
              path.push(cur);
              cur = prev.get(cur);
            }
            return path.reverse().map((numId) => numToStr[numId]);
          }
          next.push(nb);
        }
      }
    }
    frontier = next;
  }
  return null;
}

// Given a starting node and a set of target nodes (notables/keystones the
// build wants allocated), returns the full ordered list of passive ids to
// allocate to connect all of them — the "which filler nodes get me there"
// problem a build guide's numbered allocation steps solve by hand. This is
// a greedy nearest-target-first heuristic (repeatedly path to whichever
// remaining target is closest to what's already allocated), not an optimal
// Steiner tree — optimal Steiner tree is NP-hard and massive overkill here;
// greedy nearest-first is what every PoE build planner actually ships,
// since real trees are sparse enough that it rarely differs from optimal.
// The start node itself is excluded from the result: it isn't a real
// allocatable passive, just the graph's anchor.
//
// `{ ordered: true }` takes the targets in the order given instead of
// nearest-first — what a levelling guide wants, where "take the attack
// speed notable before the far-off damage cluster" matters more than the
// total route length. Each target is still reached by the shortest path
// from everything allocated so far.
function computeAllocationPath(startId, targetIds, { ordered: inGivenOrder = false } = {}) {
  const index = loadIndex();
  const numToStr = numericIdToStringId();
  const startNode = index.nodes[startId];
  if (!startNode) throw new Error(`Unknown start passive id "${startId}"`);

  const remaining = new Set(targetIds);
  for (const t of targetIds) {
    if (!index.nodes[t]) throw new Error(`Unknown target passive id "${t}"`);
  }

  const allocated = new Set([startNode.numericId]);
  const ordered = [];

  function multiSourceBFS() {
    // Distance from the whole `allocated` frontier to every reachable node,
    // plus a `prev` pointer back toward whichever allocated node it came
    // from, so any target's path back to the allocated set can be
    // reconstructed.
    const dist = new Map();
    const prev = new Map();
    let frontier = [];
    for (const nid of allocated) {
      dist.set(nid, 0);
      prev.set(nid, null);
      frontier.push(nid);
    }
    while (frontier.length) {
      const next = [];
      for (const nid of frontier) {
        const sid = numToStr[nid];
        const n = sid ? index.nodes[sid] : null;
        if (!n) continue;
        const d = dist.get(nid);
        for (const nb of traversableNeighbours(n)) {
          if (!dist.has(nb)) {
            dist.set(nb, d + 1);
            prev.set(nb, nid);
            next.push(nb);
          }
        }
      }
      frontier = next;
    }
    return { dist, prev };
  }

  while (remaining.size) {
    const { dist, prev } = multiSourceBFS();
    let closest = null;
    let closestDist = Infinity;
    // A Set iterates in insertion order, so its first entry is the next
    // target the caller listed.
    const candidates = inGivenOrder ? [remaining.values().next().value] : remaining;
    for (const t of candidates) {
      const tNumeric = index.nodes[t].numericId;
      const d = dist.get(tNumeric);
      if (d !== undefined && d < closestDist) {
        closestDist = d;
        closest = t;
      }
    }
    if (closest === null) {
      const unreachable = [...remaining].join(', ');
      throw new Error(`Target passive(s) unreachable from the allocated set: ${unreachable}`);
    }
    // Walk back from the target to whichever already-allocated node it met.
    const pathNumeric = [];
    let cur = index.nodes[closest].numericId;
    while (!allocated.has(cur)) {
      pathNumeric.push(cur);
      cur = prev.get(cur);
    }
    pathNumeric.reverse();
    for (const nid of pathNumeric) {
      allocated.add(nid);
      ordered.push(numToStr[nid]);
    }
    remaining.delete(closest);
  }

  return ordered;
}

module.exports = {
  loadIndex,
  findPassivesByName,
  resolvePassiveId,
  resolveAscendancyId,
  getClassStartNodeId,
  shortestPath,
  computeAllocationPath,
};
